#!/usr/bin/env node
/* Nutrition-data coverage report → docs/NUTRITION_COVERAGE.md
 *
 *   node tools/coverage.js            print a summary
 *   node tools/coverage.js --write    also write docs/NUTRITION_COVERAGE.md
 *   node tools/coverage.js --base REF compare with the product data at a git ref (default: the commit before
 *                                     Phase 4, 0a5f2a5), using today's catalog-matching code for both
 *
 * Counts come from WT.nut.coverage() (js/nutrition.js) — the same numbers the app shows in Settings → Nutrition.
 */
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const args = process.argv.slice(2);
const baseRef = args.includes('--base') ? args[args.indexOf('--base') + 1] : '0a5f2a5';

function load(override) {
  const ctx = { console, globalThis: null };
  ctx.globalThis = ctx;
  ctx.localStorage = { getItem: () => null, setItem() {}, removeItem() {} };
  vm.createContext(ctx);
  for (const f of ['exercises.js', 'core.js', 'engine.js', 'foods.js', 'fooddb.js', 'products.js', 'restaurants.js', 'brands.js', 'nutrition.js', 'lookup.js']) {
    const src = (override && override[f]) || fs.readFileSync(path.join(ROOT, 'js', f), 'utf8');
    vm.runInContext(src, ctx, { filename: f });
  }
  ctx.WT.load();
  return ctx.WT;
}

const WT = load();
const cov = WT.nut.coverage();
let base = null;
try {
  const old = {};
  for (const f of ['products.js', 'brands.js']) old[f] = execSync(`git show ${baseRef}:js/${f}`, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
  base = load(old).nut.coverage();
} catch (e) {
  base = null;
}

const pct = (n, d) => (d ? `${Math.round((n / d) * 100)}%` : '—');
const STATUS = { verified: 'Verified (manufacturer)', reference: 'Reference (agreeing retailer labels)', estimated: 'Estimated (sources disagree / one source)' };
const lines = [];
const out = (s) => lines.push(s === undefined ? '' : s);

out('# Branded nutrition-data coverage');
out();
out(`Generated by \`node tools/coverage.js --write\` on ${new Date().toISOString().slice(0, 10)}. The app shows the same numbers live (Settings → Nutrition → Branded coverage), including products you've saved yourself.`);
out();
out('A **branded product** here is one product line or variant in the brand catalog (`js/brands.js`) — something you can name, such as "Dave\'s Killer Bread Good Seed Thin-Sliced". Flavors with their own label are counted separately below.');
out();
out('- **Complete** — Forge holds protein, calories, carbs and fat, the label serving size and a named source.');
out('- **Partial** — Forge holds the label but at least one value wasn\'t on any source found. It is left blank (shown as "not listed"), never guessed.');
out('- **Without nutrition** — recognized, but no label on this device. Forge asks which product, then offers online search or label entry; it never borrows another product\'s numbers.');
out();
out('## Summary');
out();
out('| | Before Phase 4 | Now |');
out('|---|---:|---:|');
const row = (label, b, n) => out(`| ${label} | ${b == null ? '—' : b} | ${n} |`);
row('Branded products (catalog lines + variants)', base && base.lines, cov.lines);
row('Complete nutrition', base && `${base.complete} (${pct(base.complete, base.lines)})`, `${cov.complete} (${pct(cov.complete, cov.lines)})`);
row('Partial nutrition', base && base.partial, cov.partial);
row('Without nutrition', base && base.none, cov.none);
row('Bundled product labels (incl. per-flavor labels)', base && base.products, cov.products);
row('Products with a barcode (GS1 check digit verified)', base && base.productsWithBarcode, `${cov.productsWithBarcode} (${cov.barcodesValid}/${cov.barcodes} codes valid)`);
row('Relying on user-entered labels', '—', `${cov.userOnly} lines (on this device: ${cov.userLabels} saved labels)`);
out();
out('Bundled labels by evidence:');
out();
Object.keys(STATUS).forEach((k) => out(`- ${STATUS[k]}: **${cov.byStatus[k] || 0}**${base ? ` (before: ${base.byStatus[k] || 0})` : ''}`));
out();
out('"Before" uses the product data at the commit before this phase with the same counting code. The catalog itself also grew (frozen meals, condiments, snacks and cereal brands were added as recognized-but-unlabelled), so "without nutrition" counts include those new gaps.');
out();
out('## By category');
out();
out('| Category | Products | Complete | Partial | Without | Your labels |');
out('|---|---:|---:|---:|---:|---:|');
cov.groups.forEach((g) => out(`| ${g.group} | ${g.lines} | ${g.complete} | ${g.partial} | ${g.none} | ${g.user} |`));
out();
out('## Products with nutrition');
out();
out('| Category | Product | State | Evidence | Flavors with own label | Missing | Barcode |');
out('|---|---|---|---|---|---|---|');
cov.rows.filter((r) => r.state === 'complete' || r.state === 'partial').forEach((r) =>
  out(`| ${r.group} | ${r.brand} ${r.line} | ${r.state} | ${r.status} | ${r.flavors.join(', ') || '—'} | ${r.missing.join(', ') || '—'} | ${r.upc ? '✓' : ''} |`));
out();
out('## Most important missing products');
out();
out('Ordered by the grocery priorities for this phase (shakes & bars, yogurt, bread, deli, pasta, sauce, frozen meals, breakfast, snacks, dairy, condiments), then by how the catalog lists each brand\'s lines (main lines first). Partial entries need only the values listed.');
out();
out('| # | Category | Product | Needs |');
out('|---:|---|---|---|');
cov.missing.slice(0, 60).forEach((r, i) => out(`| ${i + 1} | ${r.group} | ${r.brand} ${r.line} | ${r.state === 'partial' ? r.missing.join(', ') : 'full label'} |`));
if (cov.missing.length > 60) out(`\n…and ${cov.missing.length - 60} more.`);
out();
out('## How these values were collected');
out();
out('This build environment could reach a web search service but not the manufacturer, retailer, USDA or Open Food Facts pages directly. The Phase 4 values were therefore read from search-result summaries of the pages linked below, not from the pages themselves, and were cross-checked across listings. That is why most new labels are **Reference data** rather than Verified, and why every conflict is kept as an Estimate with a note. Re-check a product against its package (My foods → edit → *Last checked*) to make it yours.');
out();
out('## Sources');
out();
const srcs = new Map();
(WT.PRODUCTS || []).forEach((x) => x.src && x.src.url && srcs.set(x.src.url, x.src.name));
[...srcs].forEach(([url, name]) => out(`- [${name}](${url})`));
out();

const text = lines.join('\n');
if (args.includes('--write')) {
  fs.writeFileSync(path.join(ROOT, 'docs', 'NUTRITION_COVERAGE.md'), text);
  console.log('Wrote docs/NUTRITION_COVERAGE.md');
}
console.log(`Branded products: ${cov.lines} · complete ${cov.complete} · partial ${cov.partial} · without ${cov.none} · labels ${cov.products} · barcodes ${cov.productsWithBarcode}`);
if (base) console.log(`Before (${baseRef}): ${base.lines} · complete ${base.complete} · partial ${base.partial} · without ${base.none} · labels ${base.products} · barcodes ${base.productsWithBarcode}`);
